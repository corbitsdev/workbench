// Artifact domain + presentation types for @workbench/artifact.
//
// Domain shapes (Artifact, ArtifactWithSession, ArtifactVersion, etc.) are
// owned by @workbench/shared and re-exported here so consumers can pull both
// the data model and its UI from one package. Presentation types
// (ArtifactVisual, GalleryArtifact) live here because they describe how the
// package renders artifacts, not how they are stored.

import { type } from "arktype";

export type {
  Artifact,
  ArtifactStatus,
  ArtifactVersion,
  ArtifactWithSession,
  ArtifactWithVersions,
  ArtifactKind,
  ArtifactOrigin,
  ArtifactSource,
} from "@workbench/shared";

export const ArtifactVisualSchema = type({
  label: "string",
  fill: "string",
  span: "string",
  "experimentalFill?": "string",
  "experimentalSpan?": "string",
});

export type ArtifactVisual = typeof ArtifactVisualSchema.infer;

export const GalleryArtifactSchema = ArtifactVisualSchema.and({
  id: "string",
  title: "string",
  kind: "string",
  "from?": "string",
  time: "string",
  /** "Generated by" provenance badge text, derived from the artifact source. */
  provenance: "string",
  /**
   * How the provenance badge should be presented: free-text attribution
   * (truncated, no forced casing), a coarse origin word (uppercased), or a
   * muted unknown state (chip omitted). Defaults to "origin" when absent.
   */
  "provenanceTone?": "'free'|'origin'|'unknown'",
  status: "'draft'|'approved'|'rejected'",
  "previewExcerpt?": "string",
  "thumbnailUrl?": "string",
  "thumbnailAlt?": "string",
});

export type GalleryArtifact = typeof GalleryArtifactSchema.infer;

/** Thrown when a raw object fails the GalleryArtifact schema. */
export class GalleryArtifactParseError extends Error {}

export function parseGalleryArtifact(raw: unknown): GalleryArtifact {
  const result = GalleryArtifactSchema(raw);
  if (result instanceof type.errors) {
    throw new GalleryArtifactParseError(`GalleryArtifact: ${result.summary}`);
  }
  return result;
}
