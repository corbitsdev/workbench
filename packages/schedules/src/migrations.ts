// Package-owned migrations for @corbits/schedules' one product table,
// following the same ledger pattern as `@corbits/chat`'s
// `applyChatMigrations` (see `packages/chat/src/migrations.ts`): the
// platform's own schema is authored and applied by `@intx/db` (see
// `scripts/db-setup.ts`); this module is this package's half of the
// "mount + migrations is the entire install story". Bookkeeping is its
// own table (`schedules_migrations`), never the platform's drizzle
// journal or chat's ledger, so this package's migration history stays
// extractable on its own.
import postgres from "postgres";

export interface ScheduleMigration {
  name: string;
  sql: string;
}

/**
 * Ordered, explicit migration set for the table declared in
 * `./schema.ts`. Kept as literal SQL, reviewed here, rather than
 * generated by drizzle at apply-time.
 */
export const scheduleMigrations: readonly ScheduleMigration[] = [
  {
    name: "0001_schedules",
    sql: `
      CREATE TABLE IF NOT EXISTS "schedules" (
        "id" text PRIMARY KEY,
        "tenant_id" text NOT NULL,
        "workflow_definition_id" text NOT NULL,
        "trigger" jsonb NOT NULL,
        "input" jsonb NOT NULL,
        "enabled" boolean NOT NULL DEFAULT true,
        "created_by" text NOT NULL,
        "last_run_at" timestamptz,
        "next_run_at" timestamptz NOT NULL,
        "created_at" timestamptz NOT NULL DEFAULT now(),
        "updated_at" timestamptz NOT NULL DEFAULT now()
      );
    `,
  },
  {
    name: "0002_schedules_due_index",
    sql: `
      CREATE INDEX IF NOT EXISTS "schedules_due_idx"
        ON "schedules" ("enabled", "next_run_at");
    `,
  },
];

const LEDGER_TABLE = "schedules_migrations";

function quoteIdentifier(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

export interface ApplyScheduleMigrationsReport {
  applied: string[];
  alreadyApplied: string[];
}

/**
 * Apply `scheduleMigrations` against `databaseUrl`, idempotently: a
 * migration already recorded in the ledger is skipped, never re-run.
 * Failures are loud — the migration name and the underlying error are
 * both surfaced, since a partial apply here would otherwise fail
 * silently at the next `workbench setup`.
 */
export async function applyScheduleMigrations(
  databaseUrl: string,
): Promise<ApplyScheduleMigrationsReport> {
  const sql = postgres(databaseUrl, { max: 1, onnotice: () => undefined });
  try {
    await sql.unsafe(
      `CREATE TABLE IF NOT EXISTS ${quoteIdentifier(LEDGER_TABLE)} (` +
        `name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())`,
    );
    const rows = await sql.unsafe(
      `SELECT name FROM ${quoteIdentifier(LEDGER_TABLE)}`,
    );
    const alreadyApplied = new Set(rows.map((row) => String(row["name"])));
    const applied: string[] = [];
    for (const migration of scheduleMigrations) {
      if (alreadyApplied.has(migration.name)) continue;
      try {
        await sql.unsafe(migration.sql);
        await sql.unsafe(
          `INSERT INTO ${quoteIdentifier(LEDGER_TABLE)} (name) VALUES ($1)`,
          [migration.name],
        );
        applied.push(migration.name);
      } catch (error) {
        throw new Error(
          `@corbits/schedules migration ${JSON.stringify(migration.name)} failed: ` +
            `${error instanceof Error ? error.message : String(error)}`,
          { cause: error },
        );
      }
    }
    return { applied, alreadyApplied: [...alreadyApplied] };
  } finally {
    await sql.end();
  }
}
